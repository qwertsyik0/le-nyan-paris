(() => {
  function addUniqueEntryFirst(list, entry) {
    if (!Array.isArray(list)) return;
    if (list.some((item) => item.title === entry.title)) return;
    list.unshift(entry);
  }

  function applyCurfewPatch() {
    try {
      if (typeof decrees !== 'undefined' && Array.isArray(decrees)) {
        addUniqueEntryFirst(decrees, {
          date: '29 сентября 1808',
          title: 'О ночном запрете выхода',
          text: 'В связи с нападениями, убийствами и беспорядками на улицах Парижа обычным гражданам запрещается покидать дома с 22:00 и до рассвета без крайней необходимости, письменного разрешения, служебной причины или сопровождения жандармерии. Трактиры, лавки, рынки и иные городские места должны прекратить работу до наступления установленного часа. Жандармерия получает право останавливать, допрашивать и доставлять нарушителей в тюрьму до выяснения личности и причины выхода. Врачам, жандармам, военным, служащим суда, тюрьмы и императорской канцелярии разрешено передвигаться ночью только по служебной необходимости. Гражданам велено заранее запастись едой, водой и необходимыми припасами.'
        });
      }

      if (typeof newsItems !== 'undefined' && Array.isArray(newsItems)) {
        addUniqueEntryFirst(newsItems, {
          date: '29 сентября 1808',
          type: 'указ',
          title: 'После 22:00 улицы должны быть пусты',
          text: 'После новой волны нападений император ввел ночной запрет выхода для обычных граждан. С 22:00 до рассвета городские улицы должны опустеть, а нарушителей жандармерия вправе задерживать и доставлять в тюрьму до выяснения причин выхода.'
        });
        addUniqueEntryFirst(newsItems, {
          date: '29 сентября 1808',
          type: 'объявление',
          title: 'Гражданам велено запастись припасами до ночи',
          text: 'Канцелярия предупреждает жителей Парижа: еду, воду и необходимые припасы следует подготовить заранее. После 22:00 лавки, рынки, трактиры и другие городские места должны прекратить работу.'
        });
      }

      if (typeof renderDecrees === 'function') renderDecrees();
      if (typeof renderNews === 'function') renderNews();
    } catch (error) {
      console.warn('curfew patch skipped', error);
    }
  }

  applyCurfewPatch();
  setTimeout(applyCurfewPatch, 300);
  setTimeout(applyCurfewPatch, 1200);
})();
